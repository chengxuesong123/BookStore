    }

    $pref = $prefixes[$key];
    $suf = $suffixes;
    $pi = 0;
    $si = 0;
    while ($need > 0) {
        $title = $pref[$pi % count($pref)] . $suf[$si % count($suf)];
        $pi++;
        if ($pi % count($pref) === 0) $si++;
        // 用组合继续补齐，实在重复就加数字卷
        $candidate = $title;
        $n = 1;
        while (isset($usedTitles[$candidate])) {
            $n++;
            $candidate = $title . '·第' . $n . '卷';
        }
        $title = $candidate;
        $usedTitles[$title] = true;

        $h = crc32($title . $key);
        $author = $authorFamily[$h % count($authorFamily)] . $authorGiven[($h >> 3) % count($authorGiven)] . (($h % 7 === 0) ? '·' . $authorGiven[($h >> 5) % count($authorGiven)] : '');
