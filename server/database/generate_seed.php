        if ($need <= 0) break;
        $title = $e[0];
        if (isset($usedTitles[$title])) continue;
        $usedTitles[$title] = true;
        $id++;
        $ch = crc32($title . $key);
        $stock = 5 + ($ch % 26);
        $rows[] = [$id, $idx + 1, $title, $e[1], $e[2], $e[3], $e[4], $stock, '', $e[5], $e[6]];
