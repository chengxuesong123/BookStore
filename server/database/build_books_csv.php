foreach ($targets as $category => $target) {
    $count = 0;
    foreach ($data[$category] as [$title, $author]) {
        if ($count >= $target) break;
        if (isset($seen[$title])) continue;
        $seen[$title] = true;

        $h = crc32($title . $author);
        $publisher = $publishers[$category][$h % count($publishers[$category])];
        $price = round(25 + (($h >> 3) % 950) / 10, 1);
        $original = round($price * 1.25, 1);
        $stock = ($h % 19 === 0) ? ($h % 4) : (5 + ($h % 26));
